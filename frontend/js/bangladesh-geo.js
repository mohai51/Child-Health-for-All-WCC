/**
 * Initialize District and Upazila Searchable Selector with Pourashava & Ward Support
 */
function initDistrictUpazilaSelector({
  districtInputId = 'district-input',
  upazilaSelectId = 'upazila-select',
  pourashavaCheckId = 'is-pourashava-check',
  pourashavaBoxId = 'pourashava-box',
  wardSelectId = 'ward-select',
  initialDistrict = '',
  initialUpazila = ''
}) {
  const districtInput = document.getElementById(districtInputId);
  const upazilaSelect = document.getElementById(upazilaSelectId);
  const pourashavaCheck = document.getElementById(pourashavaCheckId);
  const pourashavaBox = document.getElementById(pourashavaBoxId);

  if (!districtInput || !upazilaSelect) return;

  // Create a datalist for District Auto-Suggestion
  let datalist = document.getElementById(`${districtInputId}-datalist`);
  if (!datalist) {
    datalist = document.createElement('datalist');
    datalist.id = `${districtInputId}-datalist`;
    document.body.appendChild(datalist);
  }

  // Populate Datalist with all 64 districts
  const districtNames = Object.keys(BANGLADESH_GEO_DATA).sort((a, b) => a.localeCompare(b, 'bn'));
  datalist.innerHTML = districtNames.map(d => `<option value="${d}">${d}</option>`).join('');
  districtInput.setAttribute('list', `${districtInputId}-datalist`);
  districtInput.setAttribute('autocomplete', 'off');

  function resolveDistrict(inputVal) {
    if (!inputVal) return '';
    const trimmed = inputVal.trim();
    if (BANGLADESH_GEO_DATA[trimmed]) return trimmed;
    const lower = trimmed.toLowerCase();
    if (ENGLISH_TO_BANGLA_DISTRICTS[lower]) {
      return ENGLISH_TO_BANGLA_DISTRICTS[lower];
    }
    for (const [bnName] of Object.entries(BANGLADESH_GEO_DATA)) {
      if (bnName.includes(trimmed)) return bnName;
    }
    return trimmed;
  }

  function updateUpazilas(districtName) {
    const resolved = resolveDistrict(districtName);
    const upazilas = BANGLADESH_GEO_DATA[resolved];

    if (upazilas && upazilas.length > 0) {
      if (districtInput.value !== resolved) {
        districtInput.value = resolved;
      }
      upazilaSelect.innerHTML = `
        <option value="">-- উপজেলা নির্বাচন করুন --</option>
        ${upazilas.map(u => `<option value="${u}">${u}</option>`).join('')}
      `;
      upazilaSelect.disabled = false;
      if (initialUpazila && upazilas.includes(initialUpazila)) {
        upazilaSelect.value = initialUpazila;
      }
    } else {
      upazilaSelect.innerHTML = '<option value="">-- প্রথমে সঠিক জেলা নির্বাচন করুন --</option>';
      upazilaSelect.disabled = true;
    }
  }

  districtInput.addEventListener('input', (e) => {
    updateUpazilas(e.target.value);
  });

  districtInput.addEventListener('change', (e) => {
    updateUpazilas(e.target.value);
  });

  // Handle Pourashava Checkbox Toggle
  if (pourashavaCheck && pourashavaBox) {
    pourashavaCheck.addEventListener('change', () => {
      pourashavaBox.style.display = pourashavaCheck.checked ? 'block' : 'none';
    });
  }

  // Populate initial values if provided
  if (initialDistrict) {
    districtInput.value = initialDistrict;
    updateUpazilas(initialDistrict);
  } else {
    updateUpazilas('');
  }
}

// Global helper to programmatically set district and cascading upazila
window.setSelectorDistrictAndUpazila = function(districtInputId, upazilaSelectId, district, upazila) {
  const dInput = document.getElementById(districtInputId);
  const uSelect = document.getElementById(upazilaSelectId);
  if (dInput) {
    dInput.value = district || '';
  }
  if (uSelect) {
    const trimmed = (district || '').trim();
    const upazilas = BANGLADESH_GEO_DATA[trimmed] || [];
    if (upazilas.length > 0) {
      uSelect.innerHTML = `
        <option value="">-- উপজেলা নির্বাচন করুন --</option>
        ${upazilas.map(u => `<option value="${u}" ${u === upazila ? 'selected' : ''}>${u}</option>`).join('')}
      `;
      uSelect.disabled = false;
      if (upazila && upazilas.includes(upazila)) {
        uSelect.value = upazila;
      }
    } else {
      uSelect.innerHTML = '<option value="">-- প্রথমে সঠিক জেলা নির্বাচন করুন --</option>';
      uSelect.disabled = true;
    }
  }
};
